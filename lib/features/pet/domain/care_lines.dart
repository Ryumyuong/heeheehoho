  static List<String> of(CareAction action) => switch (action) {
        CareAction.feed => feed,
        CareAction.sleep => sleep,
        CareAction.play => play,
      };

  /// [action]에 어울리는 말 한 줄. 직전에 나온 말은 피해서 고른다.
  static String pick(CareAction action) {
    final list = of(action);
    if (list.isEmpty) return '';
    if (list.length == 1) return list.first;

    final last = _last[action];
    String line;
    do {
      line = list[_rng.nextInt(list.length)];
    } while (line == last);
    _last[action] = line;
    return line;
  }
